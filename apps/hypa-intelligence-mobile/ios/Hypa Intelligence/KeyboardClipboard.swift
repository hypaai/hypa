import UIKit

struct KeyboardClip {
  let text: String
  let pinned: Bool
  let copiedAt: Date
}

final class KeyboardClipStore {
  static let shared = KeyboardClipStore()

  private static let maxUnpinnedClips = 15
  private static let maxPinnedClips = 5
  private static let unpinnedTTL: TimeInterval = 60 * 60
  private static let fileName = "clipboard_history.json"
  private static let optedInKey = "clipboard_history_opted_in"
  private static let changeCountKey = "clipboard_last_change_count"

  private static let skippedPasteboardTypes = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
  ]

  private let lock = NSLock()

  private init() {}

  private(set) var isOptedIn: Bool = UserDefaults.standard.bool(forKey: optedInKey)

  func optIn() {
    guard !isOptedIn else { return }
    isOptedIn = true
    UserDefaults.standard.set(true, forKey: Self.optedInKey)
  }

  private var storeURL: URL {
    keyboardDataContainerURL().appendingPathComponent(Self.fileName)
  }

  func clips() -> [KeyboardClip] {
    lock.lock()
    defer { lock.unlock() }
    let stored = read()
    let now = Date()
    let alive = stored.filter {
      $0.pinned || now.timeIntervalSince($0.copiedAt) < Self.unpinnedTTL
    }
    if alive.count != stored.count { write(alive) }
    return alive
  }

  func record(_ text: String) {
    let text = text.precomposedStringWithCanonicalMapping
    lock.lock()
    defer { lock.unlock() }
    guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
    let stored = read()
    if stored.max(by: { $0.copiedAt < $1.copiedAt })?.text == text { return }
    let entry = KeyboardClip(
      text: text,
      pinned: stored.first { $0.text == text }?.pinned ?? false,
      copiedAt: Date())
    write([entry] + stored.filter { $0.text != text })
  }

  func setPinned(_ text: String, _ pinned: Bool) -> Bool {
    lock.lock()
    defer { lock.unlock() }
    let stored = read()
    guard let target = stored.first(where: { $0.text == text }) else { return false }
    if pinned, !target.pinned, stored.filter(\.pinned).count >= Self.maxPinnedClips { return false }
    let toggledAt = !pinned && target.pinned ? Date() : target.copiedAt
    write(
      stored.map {
        $0.text == text
          ? KeyboardClip(text: $0.text, pinned: pinned, copiedAt: toggledAt) : $0
      })
    return true
  }

  func delete(_ text: String) {
    lock.lock()
    defer { lock.unlock() }
    write(read().filter { $0.text != text })
  }

  func captureCurrentClip() {
    let pasteboard = UIPasteboard.general
    let changeCount = pasteboard.changeCount
    guard changeCount != UserDefaults.standard.integer(forKey: Self.changeCountKey) else { return }
    guard pasteboard.hasStrings,
      !pasteboard.contains(pasteboardTypes: Self.skippedPasteboardTypes)
    else {
      UserDefaults.standard.set(changeCount, forKey: Self.changeCountKey)
      return
    }
    guard let text = pasteboard.string else { return }
    UserDefaults.standard.set(changeCount, forKey: Self.changeCountKey)
    record(text)
  }

  func setCurrentClip(_ text: String) {
    UIPasteboard.general.string = text
    UserDefaults.standard.set(UIPasteboard.general.changeCount, forKey: Self.changeCountKey)
  }

  private func read() -> [KeyboardClip] {
    guard let data = try? Data(contentsOf: storeURL),
      let rows = (try? JSONSerialization.jsonObject(with: data)) as? [[String: Any]]
    else { return [] }
    return rows.compactMap { row in
      guard let text = row["text"] as? String, !text.isEmpty else { return nil }
      return KeyboardClip(
        text: text,
        pinned: row["pinned"] as? Bool ?? false,
        copiedAt: Date(timeIntervalSince1970: row["copiedAt"] as? TimeInterval ?? 0))
    }
  }

  private func write(_ clips: [KeyboardClip]) {
    let pinned = clips.filter(\.pinned).sorted { $0.copiedAt > $1.copiedAt }
      .prefix(Self.maxPinnedClips)
    let unpinned = clips.filter { !$0.pinned }.sorted { $0.copiedAt > $1.copiedAt }
      .prefix(Self.maxUnpinnedClips)
    let rows =
      (pinned + unpinned).map {
        ["text": $0.text, "pinned": $0.pinned, "copiedAt": $0.copiedAt.timeIntervalSince1970]
          as [String: Any]
      }
    guard let data = try? JSONSerialization.data(withJSONObject: rows) else { return }
    try? data.write(to: storeURL, options: [.atomic, .completeFileProtection])
    excludeFromBackup()
  }

  private func excludeFromBackup() {
    var url = storeURL
    var values = URLResourceValues()
    values.isExcludedFromBackup = true
    try? url.setResourceValues(values)
  }
}

final class ClipboardPanelView: UIView {
  private static let tips = [
    "Text you copy is added the next time the keyboard opens.",
    "Tap a clip to paste it.",
    "Touch and hold a clip to pin it. Unpinned clips are deleted after an hour.",
    "Use the edit icon to delete clips.",
  ]

  private static let fullAccessTips = [
    "Clipboard needs Full Access.",
    "Open Settings › General › Keyboard › Keyboards › Hypa and turn on Allow Full Access.",
  ]

  private let theme: KeyboardTheme
  private let fontSize: CGFloat
  private let isEditing: Bool
  private let onPaste: (String) -> Void
  private let onTogglePin: (KeyboardClip) -> Void
  private let onDelete: (String) -> Void

  private let scroll = UIScrollView()
  private let column = UIStackView()

  init(
    clips: [KeyboardClip],
    hasFullAccess: Bool,
    theme: KeyboardTheme,
    fontSize: CGFloat,
    isEditing: Bool,
    onPaste: @escaping (String) -> Void,
    onTogglePin: @escaping (KeyboardClip) -> Void,
    onDelete: @escaping (String) -> Void
  ) {
    self.theme = theme
    self.fontSize = fontSize
    self.isEditing = isEditing
    self.onPaste = onPaste
    self.onTogglePin = onTogglePin
    self.onDelete = onDelete
    super.init(frame: .zero)

    backgroundColor = .clear
    buildScroll()

    if clips.isEmpty {
      column.addArrangedSubview(sectionLabel(hasFullAccess ? "Tips" : "Clipboard is off"))
      (hasFullAccess ? Self.tips : Self.fullAccessTips).forEach {
        column.addArrangedSubview(tipCard($0))
      }
      return
    }
    let pinned = clips.filter { $0.pinned }
    let recent = clips.filter { !$0.pinned }
    if !pinned.isEmpty {
      column.addArrangedSubview(sectionLabel("Pinned"))
      rows(pinned).forEach { column.addArrangedSubview($0) }
    }
    if !recent.isEmpty {
      column.addArrangedSubview(sectionLabel("Recent"))
      rows(recent).forEach { column.addArrangedSubview($0) }
    }
  }

  required init?(coder: NSCoder) {
    fatalError("init(coder:) has not been implemented")
  }

  private func buildScroll() {
    scroll.translatesAutoresizingMaskIntoConstraints = false
    scroll.showsVerticalScrollIndicator = false
    addSubview(scroll)

    column.translatesAutoresizingMaskIntoConstraints = false
    column.axis = .vertical
    column.alignment = .fill
    column.spacing = 6
    scroll.addSubview(column)

    NSLayoutConstraint.activate([
      scroll.topAnchor.constraint(equalTo: topAnchor),
      scroll.leadingAnchor.constraint(equalTo: leadingAnchor, constant: 8),
      scroll.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -8),
      scroll.bottomAnchor.constraint(equalTo: bottomAnchor),
      column.topAnchor.constraint(equalTo: scroll.contentLayoutGuide.topAnchor, constant: 8),
      column.leadingAnchor.constraint(equalTo: scroll.contentLayoutGuide.leadingAnchor),
      column.trailingAnchor.constraint(equalTo: scroll.contentLayoutGuide.trailingAnchor),
      column.bottomAnchor.constraint(equalTo: scroll.contentLayoutGuide.bottomAnchor, constant: -10),
      column.widthAnchor.constraint(equalTo: scroll.frameLayoutGuide.widthAnchor),
    ])
  }

  private func rows(_ clips: [KeyboardClip]) -> [UIStackView] {
    stride(from: 0, to: clips.count, by: 2).map { start in
      let row = UIStackView()
      row.axis = .horizontal
      row.alignment = .fill
      row.distribution = .fillEqually
      row.spacing = 6
      row.addArrangedSubview(card(clips[start]))
      if start + 1 < clips.count {
        row.addArrangedSubview(card(clips[start + 1]))
      } else {
        row.addArrangedSubview(UIView())
      }
      return row
    }
  }

  private func card(_ clip: KeyboardClip) -> UIView {
    let card = ClipCardView()
    card.applyKeyAesthetics(
      background: theme.key, cornerRadius: KeySurface.controlRadius,
      tint: KeySurface.glyphTint)
    card.accessibilityLabel = clip.text
    card.heightAnchor.constraint(equalToConstant: 74).isActive = true

    let preview = UILabel()
    preview.translatesAutoresizingMaskIntoConstraints = false
    preview.text = clip.text
    preview.textColor = theme.label
    preview.font = .systemFont(ofSize: max(fontSize - 9, 11))
    preview.numberOfLines = 3
    preview.lineBreakMode = .byTruncatingTail
    card.addSubview(preview)

    let hasBadge = isEditing || clip.pinned
    NSLayoutConstraint.activate([
      preview.topAnchor.constraint(equalTo: card.topAnchor, constant: 8),
      preview.leadingAnchor.constraint(equalTo: card.leadingAnchor, constant: 10),
      preview.trailingAnchor.constraint(
        equalTo: card.trailingAnchor, constant: hasBadge ? -30 : -8),
      preview.bottomAnchor.constraint(lessThanOrEqualTo: card.bottomAnchor, constant: -8),
    ])

    if isEditing {
      card.addSubview(badge(symbol: "xmark", tint: theme.label, filled: true) { [weak self] in
        self?.onDelete(clip.text)
      })
    } else if clip.pinned {
      card.addSubview(badge(symbol: "pin.fill", tint: theme.accent, filled: false, action: nil))
    }

    card.addGestureRecognizer(
      UITapGestureRecognizer(target: card, action: #selector(ClipCardView.handleTap)))
    let hold = UILongPressGestureRecognizer(
      target: card, action: #selector(ClipCardView.handleHold(_:)))
    card.addGestureRecognizer(hold)
    card.onTap = { [weak self] in self?.onPaste(clip.text) }
    card.onHold = { [weak self] in self?.onTogglePin(clip) }
    return card
  }

  private func badge(
    symbol: String, tint: UIColor, filled: Bool, action: (() -> Void)?
  ) -> UIView {
    let button = UIButton(type: .system)
    button.translatesAutoresizingMaskIntoConstraints = false
    button.setImage(
      UIImage(
        systemName: symbol,
        withConfiguration: UIImage.SymbolConfiguration(pointSize: 11, weight: .semibold)),
      for: .normal)
    button.tintColor = tint
    button.isUserInteractionEnabled = action != nil
    if filled {
      button.backgroundColor = theme.surface
      button.layer.cornerRadius = 11
      button.layer.masksToBounds = true
    }
    if let action {
      button.addAction(UIAction { _ in action() }, for: .touchUpInside)
    }
    button.accessibilityLabel = action == nil ? "Pinned" : "Delete clip"
    return BadgeContainer(button: button)
  }

  private func sectionLabel(_ text: String) -> UILabel {
    let label = UILabel()
    label.text = text
    label.textColor = theme.label.withAlphaComponent(0.6)
    label.font = .systemFont(ofSize: max(fontSize - 10, 10), weight: .medium)
    return label
  }

  private func tipCard(_ text: String) -> UIView {
    let label = PaddedLabel()
    label.text = text
    label.textColor = theme.label
    label.font = .systemFont(ofSize: max(fontSize - 10, 10))
    label.numberOfLines = 0
    label.backgroundColor = theme.key
    label.layer.cornerRadius = 12
    label.layer.masksToBounds = true
    return label
  }
}

private final class BadgeContainer: UIView {
  init(button: UIButton) {
    super.init(frame: .zero)
    translatesAutoresizingMaskIntoConstraints = false
    addSubview(button)
    NSLayoutConstraint.activate([
      widthAnchor.constraint(equalToConstant: 22),
      heightAnchor.constraint(equalToConstant: 22),
      button.topAnchor.constraint(equalTo: topAnchor),
      button.leadingAnchor.constraint(equalTo: leadingAnchor),
      button.trailingAnchor.constraint(equalTo: trailingAnchor),
      button.bottomAnchor.constraint(equalTo: bottomAnchor),
    ])
  }

  required init?(coder: NSCoder) {
    fatalError("init(coder:) has not been implemented")
  }

  override func didMoveToSuperview() {
    super.didMoveToSuperview()
    guard let card = superview else { return }
    NSLayoutConstraint.activate([
      topAnchor.constraint(equalTo: card.topAnchor, constant: 6),
      trailingAnchor.constraint(equalTo: card.trailingAnchor, constant: -6),
    ])
  }
}

private final class ClipCardView: UIView {
  var onTap: (() -> Void)?
  var onHold: (() -> Void)?

  init() {
    super.init(frame: .zero)
    isAccessibilityElement = true
  }

  required init?(coder: NSCoder) {
    fatalError("init(coder:) has not been implemented")
  }

  @objc func handleTap() {
    onTap?()
  }

  @objc func handleHold(_ recognizer: UILongPressGestureRecognizer) {
    guard recognizer.state == .began else { return }
    onHold?()
  }
}

private final class PaddedLabel: UILabel {
  private let insets = UIEdgeInsets(top: 9, left: 10, bottom: 9, right: 10)

  override func drawText(in rect: CGRect) {
    super.drawText(in: rect.inset(by: insets))
  }

  override var intrinsicContentSize: CGSize {
    let size = super.intrinsicContentSize
    return CGSize(
      width: size.width + insets.left + insets.right,
      height: size.height + insets.top + insets.bottom)
  }

  override func textRect(
    forBounds bounds: CGRect, limitedToNumberOfLines numberOfLines: Int
  ) -> CGRect {
    let rect = super.textRect(
      forBounds: bounds.inset(by: insets), limitedToNumberOfLines: numberOfLines)
    return rect.inset(
      by: UIEdgeInsets(
        top: -insets.top, left: -insets.left, bottom: -insets.bottom, right: -insets.right))
  }
}
